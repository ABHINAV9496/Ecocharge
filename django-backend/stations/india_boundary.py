_CITY_CACHE = None


def _build_city_cache():
    global _CITY_CACHE
    if _CITY_CACHE is None:
        _CITY_CACHE = [(clat, clng) for _, clat, clng, _, _ in CITIES]
    return _CITY_CACHE


def _haversine_km(lat1, lng1, lat2, lng2):
    R = 6371
    dlat = math.radians(lat2 - lat1)
    dlng = math.radians(lng2 - lng1)
    a = math.sin(dlat / 2) ** 2 + math.cos(math.radians(lat1)) * math.cos(math.radians(lat2)) * math.sin(dlng / 2) ** 2
    return R * 2 * math.asin(math.sqrt(a))


def is_within_india(lat, lng):
    n = len(INDIA_BOUNDARY)
    inside = False
    j = n - 1
    for i in range(n):
        yi, xi = INDIA_BOUNDARY[i]
        yj, xj = INDIA_BOUNDARY[j]
        if ((yi > lat) != (yj > lat)) and (lng < (xj - xi) * (lat - yi) / (yj - yi) + xi):
            inside = not inside
        j = i
    if inside:
        return True
    for poly in [ANDAMAN_BOUNDARY, LAKSHADWEEP_BOUNDARY, DIU_BOUNDARY]:
        n = len(poly)
        inside = False
        j = n - 1
        for i in range(n):
            yi, xi = poly[i]
            yj, xj = poly[j]
            if ((yi > lat) != (yj > lat)) and (lng < (xj - xi) * (lat - yi) / (yj - yi) + xi):
                inside = not inside
            j = i
        if inside:
            return True
    cities = _build_city_cache()
    for clat, clng in cities:
        if _haversine_km(lat, lng, clat, clng) <= 50:
            return True
    return False


